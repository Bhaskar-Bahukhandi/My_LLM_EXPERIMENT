"""Mode correction cannot bypass content controls or execute downloaded text."""

import hashlib
import sys
from pathlib import Path

import pytest

sys.path.insert(0, str(Path(__file__).parents[1] / "scripts"))
from corpus_mode_v2 import filter_inert, preflight, validate_entry  # noqa: E402
from corpus_targeted_acquisition import acquire_targeted  # noqa: E402


def objects(raw, mode="100755"):
    file = {
        "source": "source",
        "path": "example.py",
        "domain": "code",
        "git_blob_sha1": hashlib.sha1(b"blob " + str(len(raw)).encode() + b"\0" + raw).hexdigest(),
        "raw_bytes_from_tree": len(raw),
    }
    entry = {
        "path": file["path"],
        "mode": mode,
        "type": "blob",
        "sha": file["git_blob_sha1"],
        "size": len(raw),
    }
    return file, entry


def test_both_regular_modes_filter_bytes_without_execution(tmp_path):
    sentinel = tmp_path / "never-created"
    raw = (
        f"__import__('pathlib').Path({str(sentinel)!r}).write_text('EXECUTED')\n"
        + "# ordinary illustrative source content\n" * 12
    ).encode()
    for mode in ("100644", "100755"):
        file, entry = objects(raw, mode)
        payload, result = filter_inert(raw, file, entry)
        assert payload == raw and result["decision"] == "ELIGIBLE_FOR_DEDUP"
        assert not sentinel.exists()


@pytest.mark.parametrize(
    "prefix,reason",
    [
        (b"# SPDX-License-Identifier: GPL-3.0-only\n", "UNAPPROVED_FILE_LICENSE"),
        (b"-----BEGIN RSA PRIVATE KEY-----\n", "CREDENTIAL_OR_PRIVATE_KEY_PATTERN"),
        (b"# Automatically generated by tool\n", "GENERATED_FILE_HEADER"),
    ],
)
def test_executable_bit_never_bypasses_content_controls(prefix, reason):
    raw = prefix + b"# ordinary illustrative source content\n" * 12
    file, entry = objects(raw)
    payload, result = filter_inert(raw, file, entry)
    assert payload is None and result["reason"] == reason


def test_modes_fail_closed_and_historical_rejection_is_reproducible():
    file, entry = objects(b"source")
    calls = []
    with pytest.raises(ValueError, match="mode-100644"):
        acquire_targeted([file], {"source": {file["path"]: entry}}, acquire=calls.append)
    assert calls == []
    for mode in ("120000", "160000", "100600", "", None):
        bad = dict(entry, mode=mode)
        with pytest.raises(ValueError, match="Unsupported"):
            preflight([file], {"source": {file["path"]: bad}})
    with pytest.raises(ValueError, match="Unsupported"):
        validate_entry(file, dict(entry, type="commit"))
