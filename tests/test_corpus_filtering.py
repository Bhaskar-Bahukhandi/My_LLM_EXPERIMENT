"""Early filtering preserves retained byte spans and exposes rejection reasons."""

import hashlib
import importlib.util
from pathlib import Path

import pytest

_spec = importlib.util.spec_from_file_location(
    "filtering", Path(__file__).parents[1] / "scripts/corpus_filtering.py"
)
f = importlib.util.module_from_spec(_spec)
_spec.loader.exec_module(f)
BODY = b"A mathematical explanation of polynomials and their roots.\r\n" * 5


def test_retained_bytes_are_unchanged():
    raw = BODY + "A coefficient can be pi.\r\n".encode()
    payload, result = f.early_filter(raw, {"path": "guide.md"})
    assert payload == raw
    assert result["counts"]["post_quality"] == len(raw)


def test_footer_and_attribution_have_original_offsets():
    credit = b".. author:: Author <author@private-domain.net>\n"
    raw = credit + BODY + b"Report a Bug"
    payload, result = f.early_filter(
        raw, {"path": "guide.md", "eligible_byte_ranges": [[0, len(credit + BODY)]]}
    )
    assert payload == b".. author:: Author <>\n" + BODY
    assert len(result["removed_ranges"]) == 2


def test_secrets_and_deceptive_example_domains_are_rejected():
    for addition, reason in [
        (b"-----BEGIN PRIVATE KEY-----", "CREDENTIAL_OR_PRIVATE_KEY_PATTERN"),
        (b"Contact user@evil-example.com", "NON_EXAMPLE_CONTACT_REVIEW_REQUIRED"),
    ]:
        payload, result = f.early_filter(BODY + addition, {"path": "code.py"})
        assert payload is None and result["reason"] == reason


def test_generated_binary_and_unknown_licenses_fail_at_expected_stage():
    for prefix, reason in [
        (b"# Automatically generated\n", "GENERATED_FILE_HEADER"),
        (b"\0", "BINARY_NUL"),
        (b"# SPDX-License-Identifier: GPL-3.0\n", "UNAPPROVED_FILE_LICENSE"),
    ]:
        payload, result = f.early_filter(prefix + BODY, {"path": "code.py"})
        assert payload is None and result["reason"] == reason


def test_generated_prose_is_not_a_generated_file_declaration():
    raw = b"Tokens are generated by the lexical analyzer.\n" + BODY
    assert f.early_filter(raw, {"path": "guide.rst"})[0] == raw


def test_multiline_author_names_remain_and_contacts_have_exact_spans():
    credit = (
        b".. sectionauthor:: One <one@private.org>,\n                   Two <two@private.org>\n\n"
    )
    payload, result = f.early_filter(credit + BODY, {"path": "guide.rst"})
    assert payload == b".. sectionauthor:: One <>,\n                   Two <>\n\n" + BODY
    assert [credit[a:b] for a, b, _ in result["removed_ranges"]] == [
        b"one@private.org",
        b"two@private.org",
    ]


def test_names_examples_and_public_urls_are_retained():
    for prefix in [
        b".. author:: Ada Lovelace\n   Charles Babbage\n",
        b"# Copyright 2020 Public Author\n",
        b"Email user@example.com; https://docs.python.org/3/\n",
        b"# Output generated by Python is discussed here.\n",
        b".. The values are generated by Python.\n",
    ]:
        raw = prefix + BODY
        assert f.early_filter(raw, {"path": "guide.rst"})[0] == raw


def test_explicit_generated_file_and_embedded_credentials_reject():
    for prefix, reason in [
        (b"# This file is automatically generated.\n", "GENERATED_FILE_HEADER"),
        (b"# Generated by generator.py\n", "GENERATED_FILE_HEADER"),
        (b"# Autogenerated by Sphinx\n", "GENERATED_FILE_HEADER"),
        (b"https://user:credential@host.invalid/path\n", "EMBEDDED_CREDENTIAL_REVIEW_REQUIRED"),
    ]:
        payload, result = f.early_filter(prefix + BODY, {"path": "guide.rst"})
        assert payload is None and result["reason"] == reason


def test_codec_generator_marker_remains_excluded():
    raw = (
        b'""" Python Character Mapping Codec cp42 generated from mappings with gencodec.py.\n'
        + BODY
    )
    assert f.early_filter(raw, {"path": "code.py"})[1]["reason"] == "GENERATED_FILE_HEADER"


def test_reviewed_contact_transform_is_hash_bound_and_reconstructable():
    line = b"Illustrative user@unreserved.test\n"
    raw = line + BODY
    review = {"raw_sha256": hashlib.sha256(raw).hexdigest(), "redact_ranges": [[0, len(line)]]}
    payload, result = f.early_filter(raw, {"path": "guide.rst"}, review)
    assert payload == BODY
    assert result["removed_ranges"] == [[0, len(line), "REVIEWED_CONTACT_REDACTION"]]
    with pytest.raises(ValueError, match="does not match"):
        f.early_filter(raw + b"changed", {"path": "guide.rst"}, review)
